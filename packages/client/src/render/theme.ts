import { Container, Graphics, Text } from "pixi.js";
import type { Faction } from "@tcg/cards";
import { TIDE, type Rect } from "./layout.ts";

/**
 * What a keeper shows. The board fills it from the game state.
 * Names are already translated.
 */
export interface KeeperLook {
  cardId: string;
  name: string;
  faction: Faction;
  attack: number;
  hold: number;
  maxHold: number;
  fresh: boolean;
  mine: boolean;
}

export interface BeaconLook {
  light: number;
  mine: boolean;
  label: string;
}

/** A display object that the board can update in place. */
export interface KeeperView extends Container {
  update(look: KeeperLook): void;
  /** The part that squashes and stretches. Its origin is at the feet. Default: the view itself. */
  body?: Container;
}

export interface SiteView extends Container {
  setName(name: string | null, cardId?: string): void;
}

export type FxKind = "hit" | "puff" | "spark";

/** A dither dissolve in progress. `threshold` runs from 0 (visible) to 1 (gone). */
export interface Dissolve {
  threshold: number;
}

export interface BeaconView extends Container {
  update(look: BeaconLook): void;
}

/**
 * The visual theme. The placeholder theme draws simple shapes (plan, section 6.9).
 * The pixel art theme replaces it: it implements the same interface with sprites.
 */
export interface Theme {
  /** Text resolution: the canvas scale, so text stays sharp. */
  resolution: number;
  background(): Container;
  slot(rect: Rect, mine: boolean): Container;
  keeper(rect: Rect, look: KeeperLook): KeeperView;
  beacon(rect: Rect, look: BeaconLook): BeaconView;
  site(rect: Rect, name: string | null): SiteView;
  tideGauge(): Container;
  tideMarker(): Container;
  highlight(rect: Rect): Container;
  floatingText(text: string, color: number): Container;
  /** Optional: a short effect sprite that destroys itself at the end. */
  fx?(kind: FxKind, tint?: number): Container;
  /** Optional: the illustration of a card, to show a played card on the board. */
  cardGhost?(cardId: string): Container | null;
  /** Optional: starts a dither dissolve on the target (plan, section 7.3). */
  dissolve?(target: Container): Dissolve;
}

export const FACTION_COLORS: Record<Faction, number> = {
  forge: 0xc8553d,
  abyss: 0x2d4b73,
  sprout: 0x4f9d69,
  gear: 0xb08d57,
  vesper: 0x7a5c99,
  neutral: 0x8a8a8a,
};

const INK = 0xf2e9d8;
const SEA = 0x0e1a24;
const FONT = "monospace";

function label(text: string, size: number, color: number, resolution: number): Text {
  const t = new Text({ text, style: { fontFamily: FONT, fontSize: size, fill: color }, resolution });
  return t;
}

/** Placeholder theme: shapes and plain text, generated by code. */
export class ShapeTheme implements Theme {
  constructor(public resolution: number) {}

  background(): Container {
    const g = new Graphics().rect(0, 0, 480, 270).fill(SEA);
    // The site column in the middle of the board.
    g.rect(216, 26, 48, 152).fill({ color: 0x173042 });
    return g;
  }

  slot(r: Rect, mine: boolean): Container {
    return new Graphics().roundRect(r.x, r.y, r.w, r.h, 3).stroke({ color: mine ? 0x3b5b70 : 0x4a3b45, width: 1 });
  }

  keeper(r: Rect, look: KeeperLook): KeeperView {
    const c = new Container() as KeeperView;
    c.position.set(r.x + r.w / 2, r.y + r.h / 2);
    const body = new Graphics();
    const name = label("", 6, INK, this.resolution);
    const stats = label("", 8, INK, this.resolution);
    name.position.set(-r.w / 2 + 4, -r.h / 2 + 3);
    stats.anchor.set(1, 1);
    stats.position.set(r.w / 2 - 4, r.h / 2 - 2);
    c.addChild(body, name, stats);
    c.update = (l: KeeperLook) => {
      body.clear();
      body.roundRect(-r.w / 2, -r.h / 2, r.w, r.h, 3).fill(FACTION_COLORS[l.faction]);
      body.roundRect(-r.w / 2, -r.h / 2, r.w, r.h, 3).stroke({ color: l.mine ? 0x9fd3f0 : 0xf0a0a0, width: 1 });
      name.text = l.name.length > 10 ? `${l.name.slice(0, 9)}…` : l.name;
      stats.text = `${l.attack}/${l.hold}`;
      stats.style.fill = l.hold < l.maxHold ? 0xffb0a0 : INK;
      c.alpha = l.fresh ? 0.75 : 1;
    };
    c.update(look);
    return c;
  }

  beacon(r: Rect, look: BeaconLook): BeaconView {
    const c = new Container() as BeaconView;
    c.position.set(r.x, r.y);
    const bar = new Graphics();
    const text = label("", 8, INK, this.resolution);
    text.anchor.set(0.5, 0);
    text.position.set(r.w / 2, r.h - 12);
    c.addChild(bar, text);
    c.update = (l: BeaconLook) => {
      bar.clear();
      bar.roundRect(14, 4, 20, 30, 2).fill(0x1f2a33);
      const h = (30 * l.light) / 10;
      if (l.light > 0) bar.roundRect(14, 34 - h, 20, h, 2).fill(l.mine ? 0xe8c547 : 0xe07a3f);
      text.text = l.light > 0 ? String(l.light) : "×";
    };
    c.update(look);
    return c;
  }

  site(r: Rect, name: string | null): SiteView {
    const c = new Container() as SiteView;
    c.position.set(r.x, r.y);
    const bg = new Graphics().roundRect(2, 2, r.w - 4, r.h - 4, 2).stroke({ color: 0x5f7f8f, width: 1 });
    const text = label("", 6, 0xbfd8e0, this.resolution);
    text.anchor.set(0.5);
    text.position.set(r.w / 2, r.h / 2);
    c.addChild(bg, text);
    c.setName = (n) => {
      text.text = n ? (n.length > 10 ? `${n.slice(0, 9)}…` : n) : "—";
      bg.alpha = n ? 1 : 0.3;
    };
    c.setName(name);
    return c;
  }

  tideGauge(): Container {
    const g = new Graphics();
    for (let i = 0; i < TIDE.cells; i++) {
      g.rect(TIDE.x + i * TIDE.cell, TIDE.y, TIDE.cell - 1, TIDE.cell).fill(i === 5 ? 0x2a5070 : 0x1d3b52);
    }
    return g;
  }

  tideMarker(): Container {
    const g = new Graphics().rect(-3, -1, 6, TIDE.cell + 2).fill(0x8fd3ff);
    g.y = TIDE.y;
    return g;
  }

  highlight(r: Rect): Container {
    return new Graphics().roundRect(r.x - 1, r.y - 1, r.w + 2, r.h + 2, 4).stroke({ color: 0xfff1a8, width: 1 });
  }

  floatingText(text: string, color: number): Container {
    const t = label(text, 9, color, this.resolution);
    t.anchor.set(0.5);
    return t;
  }
}
