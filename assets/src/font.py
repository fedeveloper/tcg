BASES = {"grave": "aeiouAEIOU", "acute": "aeiouAEIOU", "circ": "aeiouAEIOU", "diaer": "aeiouAEIOU", "tilde": "nNao"}
ALIASES = {"’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-"}


def _rows(s):
    return s.split("/")


def build(font):
    """Returns {char: (width, {(x, y)})}. y = 0 is the top of the line."""
    cap, above = font["cap"], font["above"]
    out = {}
    for ch, s in font["glyphs"].items():
        rows = _rows(s)
        w = max(len(r) for r in rows)
        out[ch] = (w, {(x, above + y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"})
    for kind, chars in COMPOSED.items():
        acc = _rows(font["accents"][kind])
        aw = max(len(r) for r in acc)
        for ch, base in zip(chars, BASES[kind]):
            lower = base.islower()
            src = "ı" if base == "i" else base
            bw, pts = out[src]
            w = max(bw, aw)
            bx = (w - bw) // 2
            if base == "i":
                bx = {"grave": w - bw, "acute": 0}.get(kind, bx)
            ax = (w - aw) // 2
            # Faro lower case: the accent sits one row above the x-height
            top = above - 1 if (lower and font is FARO) else above - len(acc)
            g = {(x + bx, y) for x, y in pts}
            g |= {(ax + x, top + y) for y, r in enumerate(acc) for x, c in enumerate(r) if c == "#"}
            out[ch] = (w, g)
    ced = _rows(font["cedilla"])
    for ch, base in (("ç", "c"), ("Ç", "C")):
        bw, pts = out[base]
        out[ch] = (bw, set(pts) | {(x, above + cap + y) for y, r in enumerate(ced) for x, c in enumerate(r) if c == "#"})
    for alias, src in ALIASES.items():
        out[alias] = out[src]
    out[" "] = (font["space"], set())
    return out


def line_height(font):
    return font["above"] + font["cap"] + font["below"]


_CACHE = {}


def glyphs(font):
    key = id(font)
    if key not in _CACHE:
        _CACHE[key] = build(font)
    return _CACHE[key]


def measure(font, text):
    g = glyphs(font)
    return sum(g.get(ch, g["?"])[0] + 1 for ch in text) - 1 if text else 0


def draw_text(canvas, font, text, x, y, col):
    """Draws text on a Canvas. (x, y) is the top left corner of the line box."""
    g = glyphs(font)
    for ch in text:
        w, pts = g.get(ch, g["?"])
        canvas.fill({(x + px, y + py) for px, py in pts}, col)
        x += w + 1
    return x


def wrap(font, text, width):
    lines, cur = [], ""
    for word in text.split(" "):
        trial = (cur + " " + word).strip()
        if measure(font, trial) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    return lines + [cur] if cur else lines


def atlas(font, name, png_name):
    """Returns the atlas image and the BMFont text description."""
    g = glyphs(font)
    lh = line_height(font)
    chars = sorted(g)
    x = y = 0
    width = 128
    cells = {}
    for ch in chars:
        w = max(g[ch][0], 1)
        if x + w + 1 > width:
            x, y = 0, y + lh + 1
        cells[ch] = (x, y, w)
        x += w + 1
    height = 1
    while height < y + lh:
        height *= 2
    im = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    px = im.load()
    lines = [
        f'info face="{name}" size={lh} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={lh + 1} base={font['above'] + font['cap']} scaleW={width} scaleH={height} pages=1 packed=0",
        f'page id=0 file="{png_name}"',
        f"chars count={len(chars)}",
    ]
    for ch in chars:
        cx, cy, w = cells[ch]
        for gx, gy in g[ch][1]:
            px[cx + gx, cy + gy] = (255, 255, 255, 255)
        lines.append(
            f"char id={ord(ch)} x={cx} y={cy} width={w} height={lh} xoffset=0 yoffset=0 xadvance={g[ch][0] + 1} page=0 chnl=15"
        )
    return im, "\n".join(lines) + "\n"
